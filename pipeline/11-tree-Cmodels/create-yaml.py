#!/usr/bin/env python3
"""
Create YAML configuration file for tree editing pipeline.
Scans the homologs and combined_tree folders to generate a complete list of proteins.
"""

import os
import re

# Directories
HOMOLOGS_DIR = "../../output/seqs/homologs"
COMBINED_DIR = "../../output/seqs/combined_tree"
OUTPUT_YAML = "../12-final-edit-tree/edit_all.yaml"

# Special proteins that use a01 suffix instead of r01/r00
SPECIAL_PROTEINS = ['Tuc1', 'TRM9B']

# Combined protein prefixes (individual proteins that are part of combined trees)
COMBINED_PREFIXES = ['TadA', 'ADAT2', 'MnmA', 'MTU1', 'Tgt', 'QTRT1']


def get_protein_name(filename):
    """Extract protein name from filename."""
    # Match protein name at the start (before _k or other suffixes)
    # Handle combined names like TadA-ADAT2
    match = re.match(r'^([A-Za-z0-9]+-?[A-Za-z0-9]*)', filename)
    if match:
        return match.group(1)
    return None


def find_single_proteins():
    """Find all single protein files from homologs folder."""
    single_proteins = []
    filter_mapping = {}
    
    files = os.listdir(HOMOLOGS_DIR)
    
    # Get unique protein names first
    protein_files = {}
    
    for f in files:
        if not f.endswith('.fa'):
            continue
        
        # Skip files without r00, r01, or a01 suffix
        if not re.search(r'_(r0[01]|a01)\.fa$', f):
            continue
        
        protein_name = get_protein_name(f)
        if not protein_name:
            continue
        
        # Skip proteins that are part of combined trees
        if protein_name in COMBINED_PREFIXES:
            continue
        
        basename = f[:-3]  # Remove .fa
        
        # For special proteins (Tuc1, TRM9B), prefer a01 suffix
        if protein_name in SPECIAL_PROTEINS:
            if '_a01' in basename:
                protein_files[protein_name] = basename
            elif protein_name not in protein_files:
                protein_files[protein_name] = basename
        else:
            # For other proteins, prefer r01 over r00
            if '_r01' in basename:
                protein_files[protein_name] = basename
            elif protein_name not in protein_files:
                protein_files[protein_name] = basename
    
    # Sort by protein name
    for protein_name in sorted(protein_files.keys()):
        single_proteins.append(protein_files[protein_name])
        filter_mapping[protein_name] = protein_files[protein_name]
    
    return single_proteins, filter_mapping


def find_combined_proteins():
    """Find all combined protein files from combined_tree folder."""
    combined_proteins = []
    filter_mapping = {}
    
    if not os.path.exists(COMBINED_DIR):
        return combined_proteins, filter_mapping
    
    files = os.listdir(COMBINED_DIR)
    
    # Get unique combined protein names
    protein_files = {}
    
    for f in files:
        if not f.endswith('.fa'):
            continue
        
        basename = f[:-3]  # Remove .fa
        protein_name = get_protein_name(f)
        
        if not protein_name:
            continue
        
        # Prefer m01_r01 suffix, then m01, then base
        if '_m01_r01' in basename:
            protein_files[protein_name] = basename
        elif '_m01' in basename and protein_name not in protein_files:
            protein_files[protein_name] = basename
        elif protein_name not in protein_files:
            protein_files[protein_name] = basename
    
    # Only keep the most filtered version (m01_r01)
    for protein_name in sorted(protein_files.keys()):
        if '_m01_r01' in protein_files[protein_name]:
            combined_proteins.append(protein_files[protein_name])
            filter_mapping[protein_name] = protein_files[protein_name]
    
    return combined_proteins, filter_mapping


def create_yaml():
    """Create the complete YAML configuration file."""
    single_proteins, single_mapping = find_single_proteins()
    combined_proteins, combined_mapping = find_combined_proteins()
    
    # Merge mappings
    filter_mapping = {**single_mapping, **combined_mapping}
    
    # Create YAML content
    yaml_content = {
        'SINGLE': single_proteins,
        'COMBINED': combined_proteins,
        'FILTER_TO_PROTEIN': filter_mapping
    }
    
    # Write YAML file with comments
    with open(OUTPUT_YAML, 'w') as f:
        f.write("# Complete list of all proteins for tree editing\n")
        f.write("# SINGLE: Individual protein trees (from homologs folder)\n")
        f.write("# COMBINED: Combined protein trees (from combined_tree folder)\n")
        f.write("# Auto-generated by create-yaml.py\n\n")
        
        # Write SINGLE section
        f.write("SINGLE:\n  [\n")
        for i, protein in enumerate(single_proteins):
            if i < len(single_proteins) - 1:
                f.write(f'  "{protein}",\n')
            else:
                f.write(f'  "{protein}"\n')
        f.write("  ]\n\n")
        
        # Write COMBINED section
        f.write("COMBINED:\n  [\n")
        for i, protein in enumerate(combined_proteins):
            if i < len(combined_proteins) - 1:
                f.write(f'  "{protein}",\n')
            else:
                f.write(f'  "{protein}"\n')
        f.write("  ]\n\n")
        
        # Write FILTER_TO_PROTEIN section
        f.write("# Mapping from protein name to filter string (for file lookup)\n")
        f.write("FILTER_TO_PROTEIN:\n")
        
        # Write single protein mappings first
        f.write("  # Single proteins\n")
        for protein_name in sorted(single_mapping.keys()):
            f.write(f"  {protein_name}: {single_mapping[protein_name]}\n")
        
        # Write combined protein mappings
        f.write("  # Combined proteins\n")
        for protein_name in sorted(combined_mapping.keys()):
            f.write(f"  {protein_name}: {combined_mapping[protein_name]}\n")
    
    print(f"Created {OUTPUT_YAML}")
    print(f"  - SINGLE proteins: {len(single_proteins)}")
    print(f"  - COMBINED proteins: {len(combined_proteins)}")
    print(f"  - Total mappings: {len(filter_mapping)}")


if __name__ == "__main__":
    create_yaml()
